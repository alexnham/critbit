import * as anchor from "@coral-xyz/anchor";
import { Program } from "@coral-xyz/anchor";
import { HelloWorld } from "../programs/target/types/hello_world"; // Generated by 'anchor build'

async function callProgram() {
  // 1. Configure the client to use the local cluster provider
  console.log("hi")
  const provider = anchor.AnchorProvider.env();
  anchor.setProvider(provider);

  // 2. Load your compiled Anchor program
  const program = anchor.workspace.HelloWorld as Program<HelloWorld>;
  console.log("hi")
  try {
    // 3. Invoke the 'say_hello' instruction
    const txSignature = await program.methods
      .hello()
      .rpc();

    console.log("Transaction successfully submitted!");
    console.log(`Transaction Signature: ${txSignature}`);
    
    // You can view this signature on the Solana Explorer (switch network to Custom/Localhost)
  } catch (error) {
    console.error("Failed to call program:", error);
  }
}

callProgram();
